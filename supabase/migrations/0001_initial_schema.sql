-- Legacy role/page matrix is represented separately from auth users.
create table if not exists public.roles (
  key text primary key,
  label text not null,
  color text,
  sort_order integer not null default 0,
  is_super boolean not null default false,
  hidden_signup boolean not null default false
);

create table if not exists public.role_permissions (
  role_key text not null references public.roles(key) on delete cascade,
  page_key text not null,
  can_view boolean not null default false,
  can_add boolean not null default false,
  can_edit boolean not null default false,
  can_delete boolean not null default false,
  primary key(role_key,page_key)
);

-- Profiles link Supabase Auth users to the legacy business identity and branch scope.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  email text,
  role_key text references public.roles(key),
  status text not null default 'Active',
  branch_id bigint references public.branches(id),
  profile_image text,
  theme_mode text default 'light',
  custom_colors jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

