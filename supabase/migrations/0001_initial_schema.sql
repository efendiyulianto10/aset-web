create extension if not exists pgcrypto;

create table if not exists public.branches (
  id bigint generated by default as identity primary key,
  name text not null unique,
  type text,
  address text,
  is_active boolean not null default true,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  parent_id bigint references public.branches(id),
  loc_type text,
  manager text,
  is_stock_location boolean not null default true,
  sort_order integer
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  parent_id bigint references public.categories(id),
  icon text,
  storage_type text,
  count_freq text
);

create table if not exists public.vendors (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  is_active boolean not null default true,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.units (
  code text primary key,
  name text not null,
  kind text not null,
  base_code text not null,
  factor numeric(18,6) not null default 1,
  decimals integer not null default 0,
  is_deleted boolean not null default false
);

create table if not exists public.items (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id),
  name text not null,
  unit text,
  unit_cost numeric(18,6) not null default 0,
  item_type text,
  min_stock numeric(18,6) not null default 0,
  is_active boolean not null default true,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  item_code text unique,
  base_unit text,
  stock_unit text,
  purchase_unit text,
  issue_unit text,
  pack_qty numeric(18,6),
  photo_url text,
  storage_type text,
  shelf_life_days integer,
  yield_pct numeric(8,3) default 100,
  barcode text,
  preferred_vendor_id bigint references public.vendors(id),
  is_sellable boolean not null default false,
  is_recipe_item boolean not null default false
);

create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  grn_no text unique,
  vendor_id bigint references public.vendors(id),
  branch_id bigint references public.branches(id),
  vendor_invoice_no text,
  purchase_date date,
  total_amount numeric(18,6) not null default 0,
  status text,
  received_by uuid,
  notes text,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchase_items (
  id bigint generated by default as identity primary key,
  purchase_id bigint not null references public.purchases(id) on delete cascade,
  item_id bigint not null references public.items(id),
  qty numeric(18,6) not null,
  unit_cost numeric(18,6) not null default 0,
  amount numeric(18,6) not null default 0
);

create table if not exists public.purchase_requests (
  id bigint generated by default as identity primary key,
  request_no text unique,
  branch_id bigint references public.branches(id),
  to_branch_id bigint references public.branches(id),
  request_date date,
  required_date date,
  status text,
  requested_by uuid,
  approved_by uuid,
  notes text,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  priority text,
  meal_period text,
  covers numeric(18,3),
  approved_at timestamptz,
  reject_reason text
);

create table if not exists public.purchase_request_items (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.purchase_requests(id) on delete cascade,
  item_id bigint not null references public.items(id),
  requested_qty numeric(18,6) not null default 0,
  approved_qty numeric(18,6) not null default 0,
  dispatched_qty numeric(18,6) not null default 0,
  unit_cost numeric(18,6) not null default 0,
  amount numeric(18,6) not null default 0,
  line_note text,
  short_reason text
);

create table if not exists public.productions (
